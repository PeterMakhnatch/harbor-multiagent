def test_control_claims_one_trial_and_seals_outcome(
    monkeypatch: pytest.MonkeyPatch, prepared
) -> None:
    def launch(directory, harbor, env, spend_dir):
        assert spend_dir is None
        _native_output(directory, stages=("complete", "complete"))
        return 0

    monkeypatch.setattr(driver, "_launch", launch)
    result = driver._run(**prepared, arm="peer", spend_dir=None)
    cell = prepared["study"] / "controls/cf-w00-d0-r0-peer"
    assert result["status"] == "complete"
    config_data = (cell / "config.json").read_bytes()
    config = json.loads(config_data)
    assert config["trial_name"] == "calendar-control-cf-w00-d0-r0-peer"
    assert not config.get("artifacts")  # Native uses the stock task's entries.
    assert all(
        p["kwargs"]["own_starts"] == [] and "model_name" not in p
        for p in config["participants"]
    )
    attempt = json.loads((cell / "attempt.json").read_bytes())
    assert attempt["seed_sha256"] is None
    assert attempt["config_sha256"] == hashlib.sha256(config_data).hexdigest()
    assert stat.S_IMODE((cell / "outcome.json").stat().st_mode) == 0o400
    with pytest.raises(ValueError, match="attempt_already_claimed_do_not_retry"):
        driver._run(**prepared, arm="peer", spend_dir=None)
    assert json.loads((cell / "outcome.json").read_bytes()) == result


def _seeds(study: Path, first: list[int], second: list[int]) -> Path:
    root = study / "seeds/cf-w00-d0-r0"
    for directory in (study, root.parent, root):
        directory.mkdir(mode=0o700, exist_ok=True)
    for seat, value in (("p1", first), ("p2", second)):
        path = root / f"{seat}.json"
        _write(path, {"value": value})
        path.chmod(0o600)
    return root


def test_paid_arms_cannot_diverge_from_sealed_seed_pair(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, prepared
) -> None:
    root = _seeds(prepared["study"], [1], [3, 4])
    ledger = tmp_path.resolve() / "spend"
    ledger.mkdir(mode=0o700)
    monkeypatch.setattr(calendar_turns, "load_seed_pair", lambda *_: ((1,), (3, 4)))
    launched = []

    def launch(directory, harbor, env, spend_dir):
        launched.append(directory.name)
        assert spend_dir == ledger
        config = json.loads((directory / "config.json").read_bytes())
        assert [p["kwargs"]["own_starts"] for p in config["participants"]] == [
            [1],
            [3, 4],
        ]
        _native_output(directory, stages=("model_invalid", "peer_model_invalid"))
        return 0

    monkeypatch.setattr(driver, "_launch", launch)
    assert (
        driver._run(**prepared, arm="blind", spend_dir=ledger)["status"]
        == "invalid_model"
    )
    _write(root / "p1.json", {"value": [1], "changed": True})
    peer = driver._run(**prepared, arm="peer", spend_dir=ledger)
    assert peer["error"] == "first_arm_not_confirmed_with_same_seeds"
    assert launched == ["cf-w00-d0-r0-blind"]


@pytest.mark.parametrize("paid", [False, True])
def test_native_child_strips_credentials_before_harbor(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, prepared, paid: bool
) -> None:
    study = prepared["study"]
    ledger = None
    env = {"PATH": "/usr/bin", "OPENROUTER_API_KEY": "irrelevant-placeholder"}
    if paid:
        ledger = tmp_path.resolve() / "ledger"
        ledger.mkdir(mode=0o700)
        env.update(DEEPSEEK_API_KEY="host-placeholder", SEATLAB_SPEND_DIR=str(ledger))
        _seeds(study, [1], [1])
        monkeypatch.setattr(calendar_turns, "load_seed_pair", lambda *_: ((1,), (1,)))
    monkeypatch.setattr(deepseek, "_BOUND", False)
    monkeypatch.setattr(deepseek, "_KEY", None)
    monkeypatch.setattr(spend, "_HOST_LEDGER", None)
    monkeypatch.setattr(driver, "_launch", lambda *_: 1)
    assert driver._run(**prepared, arm="blind", spend_dir=ledger)["returncode"] == 1
    directory = study / ("cells" if paid else "controls") / "cf-w00-d0-r0-blind"
    config_bytes = (directory / "config.json").read_bytes()
    assert b"host-placeholder" not in config_bytes
    assert b"irrelevant-placeholder" not in config_bytes
    monkeypatch.setattr(driver.os, "environ", env)
    calls = []

    def invoke(path, *, run_name):
        calls.append((path, run_name))
        assert env == {"PATH": "/usr/bin"}
        assert deepseek._BOUND is paid
        assert spend._HOST_LEDGER == ledger
        assert driver.sys.argv[1:] == [
            "trial",
            "start",
            "-c",
            str(directory / "config.json"),
        ]

    monkeypatch.setattr(driver.runpy, "run_path", invoke)
    assert driver._host_trial(directory, prepared["harbor"]) == 0
    assert calls == [(str(prepared["harbor"]), "__main__")]
