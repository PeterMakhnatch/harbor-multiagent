def _native_output(directory: Path, *, stages: tuple[str, str]) -> None:
    config = json.loads((directory / "config.json").read_bytes())
    TrialConfig.model_validate(config)
    attempt = json.loads((directory / "attempt.json").read_bytes())
    control = attempt["mode"] == "control"
    trial = directory / "trials" / config["trial_name"]
    completed = stages == ("complete", "complete")
    caller = "p2" if completed else None
    count = int(completed)
    result = {
        "id": "00000000-1111-4000-8000-000000000001",
        "task_name": "schedule-000-talk",
        "trial_name": trial.name,
        "task_checksum": attempt["task_checksum"],
        "finished_at": "2026-01-01T01:00:00Z",
        "exception_info": None,
        "reward_valid": True,
        "verifier_result": {"rewards": {"reward": count}},
        "config": config,
        "seat_results": [
            {
                "seat": seat,
                "under_test": True,
                "exception_info": None,
                "agent_info": {
                    "name": calendar_seat.AGENT_NAME,
                    "version": calendar_seat.AGENT_VERSION,
                },
                "agent_result": {
                    "metadata": {
                        "calendar": {
                            "schema": calendar_seat.SEAT_SCHEMA,
                            "seat": seat,
                            "run": attempt["run"],
                            "stage": stage,
                            "control": control,
                        },
                    },
                },
            }
            for seat, stage in zip(("p1", "p2"), stages, strict=True)
        ],
    }
    _write(trial / "result.json", result)
    _write(trial / "config.json", config)
    _write(trial / "lock.json", {"schema_version": 1})
    _write(trial / "verifier/reward.json", {"reward": count})
    _write(
        trial / "verifier/score.json",
        {
            "score": count,
            "error": None,
            "n_submissions": count,
            "n_messages": 2,
            "submitted_by": caller,
        },
    )
    _write(
        trial / "verifier/world-state.json", {"submissions": [{"seat": caller}] * count}
    )
    for name in ("events", "messages"):
        _write(trial / f"artifacts/logs/world/{name}.jsonl", {"type": "fixture"})
    for seat, stage in zip(("p1", "p2"), stages, strict=True):
        if stage != "peer_model_invalid":
            name = "calendar-control.json" if control else "calendar-turn.json"
            _write(trial / "seats" / seat / "agent" / name, {})


