def test_native_checksum_does_not_ignore_archive_contamination(stock) -> None:
    task, checksum = stock
    assert driver._stock(task, checksum) == "schedule-000-talk"
    cache = task / "environment/__pycache__/family.cpython-312.pyc"
    cache.parent.mkdir()
    cache.write_bytes(b"added after the original run")
    with pytest.raises(ValueError, match="generated bytecode"):
        driver._stock(task, checksum)
    assert cache.read_bytes() == b"added after the original run"


def test_local_env_uses_private_home_and_an_existing_unix_socket(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    directory = tmp_path.resolve()
    monkeypatch.setattr(
        driver.shutil, "which", lambda *args, **kwargs: "/usr/bin/docker"
    )
    monkeypatch.setenv("OPENROUTER_API_KEY", "test-placeholder")
    monkeypatch.setenv("DOCKER_CONFIG", str(directory / "user-docker"))
    monkeypatch.setenv("DOCKER_HOST", "tcp://localhost:2375")
    with pytest.raises(ValueError, match="local_docker_socket_required"):
        driver._native_env(directory)
    monkeypatch.chdir(directory)
    with socket.socket(socket.AF_UNIX) as local:
        local.bind("s")
        monkeypatch.setenv("DOCKER_HOST", f"unix://{directory}/s")
        env = driver._native_env(directory)
    assert env["DOCKER_HOST"] == f"unix://{directory}/s"
    assert env["HOME"] == str(directory / "home")
    assert env["TMPDIR"] == str(directory / "tmp")
    assert env["COMPOSE_DISABLE_ENV_FILE"] == "1"
    assert set(env).isdisjoint(
        {"OPENROUTER_API_KEY", "DEEPSEEK_API_KEY", "DOCKER_CONFIG"}
    )
    for name in ("home", "tmp"):
        assert stat.S_IMODE((directory / name).stat().st_mode) == 0o700


